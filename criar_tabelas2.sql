create or replace function public.gtt_pode_acessar(p_cliente_id bigint)
returns boolean language sql stable security definer as $$
  select exists (
    select 1 from public.gtt_usuarios_acesso
    where user_id = auth.uid() and (is_staff = true or cliente_id = p_cliente_id)
  );
$$;

create policy "acesso por cliente" on public.gtt_clientes for all to authenticated using (public.gtt_pode_acessar(id)) with check (public.gtt_pode_acessar(id));
