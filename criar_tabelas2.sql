-- ── Acesso por cliente ──────────────────────────────────────────────
-- Cada usuário (P&C ou o cliente, ex: BAT/Whirlpool) só enxerga os
-- cliente_id vinculados a ele. Usuários da P&C ficam vinculados a TODOS
-- os clientes (is_staff = true); usuário de cliente só ao(s) seu(s).
create table public.gtt_usuarios_acesso (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  cliente_id bigint references public.gtt_clientes(id) on delete cascade,
  is_staff boolean not null default false,  -- true = P&C, enxerga todos os clientes
  unique (user_id, cliente_id)
);
alter table public.gtt_usuarios_acesso enable row level security;
create policy "usuário vê seu próprio acesso" on public.gtt_usuarios_acesso for select to authenticated using (user_id = auth.uid());

